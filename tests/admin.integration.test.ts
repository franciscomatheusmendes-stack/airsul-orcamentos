import { it, expect } from "vitest";
import request from "supertest";
import pg from "pg";
import { randomBytes } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { createApp } from "../server/app";
import { adminEmail, hashPassword } from "../server/session";

it.skipIf(process.env.AIRSUL_INTEGRATION_TEST !== "isolated-neon-branch")("valida autenticação, permissões, cadastros, cálculo e PDF no Neon isolado", async () => {
  if (!process.env.DATABASE_URL || !process.env.AIRSUL_TEST_HOST || new URL(process.env.DATABASE_URL).hostname !== process.env.AIRSUL_TEST_HOST) throw new Error("Banco isolado obrigatório");
  const pool = new pg.Pool({connectionString:process.env.DATABASE_URL,ssl:{rejectUnauthorized:true},max:3});
  const maintenancePool = process.env.AIRSUL_TEST_MAINTENANCE_URL ? new pg.Pool({connectionString:process.env.AIRSUL_TEST_MAINTENANCE_URL,ssl:{rejectUnauthorized:true},max:1}) : pool;
  process.env.ADMIN_ORIGIN="https://airsul-test.invalid";
  process.env.ADMIN_SETUP_TOKEN=randomBytes(32).toString("hex");
  process.env.ADMIN_ENABLED="true";
  process.env.NODE_ENV="production";
  const app=createApp(pool);
  const post=(path:string,body:unknown,cookie?:string)=>{
    const r=request(app).post(path).set("Origin",process.env.ADMIN_ORIGIN!).send(body);
    return cookie?r.set("Cookie",cookie):r;
  };
  const password=randomBytes(24).toString("hex");
  try {
    expect((await pool.query("SELECT 1 FROM admin_users LIMIT 1")).rowCount).toBe(0);
    expect((await request(app).get("/api/health")).status).toBe(200);
    expect((await request(app).get("/api/admin/materials")).status).toBe(401);
    expect((await request(app).get("/api/admin/customers")).status).toBe(401);
    expect((await post("/api/admin/quotes/preview",{})).status).toBe(401);
    expect((await request(app).get("/api/admin/quotes/00000000-0000-4000-8000-000000000000/pdf")).status).toBe(401);
    expect((await request(app).post("/api/setup").set("Origin","https://evil.invalid").send({token:process.env.ADMIN_SETUP_TOKEN,password})).status).toBe(403);
    expect((await post("/api/setup",{token:"bad",password})).status).toBe(403);
    expect((await post("/api/setup",{token:process.env.ADMIN_SETUP_TOKEN,password})).status).toBe(201);
    expect((await post("/api/setup",{token:process.env.ADMIN_SETUP_TOKEN,password})).status).toBe(409);
    expect((await post("/api/admin/login",{email:adminEmail,password:"incorrect"})).status).toBe(401);
    const login=await post("/api/admin/login",{email:adminEmail,password});
    expect(login.status).toBe(200);
    const cookie=String(login.headers["set-cookie"][0]).split(";")[0];
    expect(login.headers["set-cookie"][0]).toMatch(/HttpOnly/);
    expect(login.headers["set-cookie"][0]).toMatch(/Secure/);
    expect(login.headers["set-cookie"][0]).toMatch(/SameSite=Strict/);
    expect((await request(app).get("/api/admin/me").set("Cookie",cookie)).body.user.email).toBe(adminEmail);
    expect((await request(app).post("/api/admin/materials").set("Cookie",cookie).set("Origin","https://evil.invalid").send({})).status).toBe(403);
    expect((await post("/api/admin/materials",{name:"Inválido",unit:"m",unitCost:-1},cookie)).status).toBe(400);
    const material=await post("/api/admin/materials",{name:"Cobre teste integração",unit:"m",unitCost:50},cookie);
    expect(material.status).toBe(201);
    const customer=await post("/api/admin/customers",{name:"Cliente teste integração",phone:"51999999999",email:""},cookie);
    expect(customer.status).toBe(201);
    const input={lines:[{materialId:material.body.material.id,quantity:2,suppliedBy:"airsul"}],laborCents:20000,travelCents:0,overheadCents:0,marginPercent:25,supplyMode:"airsul",customerId:customer.body.customer.id,capacityBtu:12000,lineLengthM:3,notes:"SEGREDO_INTERNO_TESTE"};
    const preview=await post("/api/admin/quotes/preview",input,cookie);
    expect(preview.status).toBe(200);expect(preview.body.proposedPriceCents).toBe(40000);
    expect((await post("/api/admin/quotes/preview",{...input,marginPercent:100},cookie)).status).toBe(400);
    const clientPreview=await post("/api/admin/quotes/preview",{...input,supplyMode:"client",lines:[{...input.lines[0],suppliedBy:"client"}]},cookie);
    expect(clientPreview.body.materialCostCents).toBe(0);
    const saved=await post("/api/admin/quotes",input,cookie);
    expect(saved.status).toBe(201);
    const pdf=await request(app).get("/api/admin/quotes/"+saved.body.quoteId+"/pdf").set("Cookie",cookie);
    expect(pdf.status).toBe(200);expect(pdf.headers["content-type"]).toMatch(/application\/pdf/);
    expect(pdf.body.subarray(0,4).toString()).toBe("%PDF");
    await mkdir("tmp/qa",{recursive:true});await writeFile("tmp/qa/orcamento.pdf",pdf.body);
    expect((await post("/api/admin/logout",{},cookie)).status).toBe(200);
    expect((await request(app).get("/api/admin/me").set("Cookie",cookie)).status).toBe(401);
    const login2=await post("/api/admin/login",{email:adminEmail,password});
    const cookie2=String(login2.headers["set-cookie"][0]).split(";")[0];
    await maintenancePool.query("UPDATE admin_sessions SET expires_at=now()-interval '1 second'");
    expect((await request(app).get("/api/admin/me").set("Cookie",cookie2)).status).toBe(401);
    await pool.query("INSERT INTO admin_users(email,password_hash) VALUES($1,$2)",["other@example.com",hashPassword(password)]);
    expect((await post("/api/admin/login",{email:"other@example.com",password})).status).toBe(401);
    for(let i=0;i<10;i++) await post("/api/admin/login",{email:adminEmail,password:"bad"});
    expect((await post("/api/admin/login",{email:adminEmail,password:"bad"})).status).toBe(429);
    process.env.ADMIN_ENABLED="false";
    expect((await request(app).get("/api/admin/materials")).status).toBe(503);
  } finally {if(maintenancePool!==pool) await maintenancePool.end();await pool.end();}
},60000);
